/**
 * /mixpanel-boot.js, generated per request from the environment (Worker vars or `architect serve`'s
 * process.env), so the Mixpanel project token never sits in git. The token is public once served.
 *
 *   MIXPANEL_PROJECT_TOKEN   32-hex project token. Unset: Mixpanel stays off (the script is a comment).
 *   MIXPANEL_REGION          US (default), EU or IN: must match the project's data residency.
 *   MIXPANEL=off             turns it off even when a token is set.
 *
 * web/mixpanel.vendor.js (mixpanel-browser 2.85.0 core build, Apache-2.0, first-party) sends one page
 * view per load (domain + path) with product "architect". No autocapture, replay, IP geolocation,
 * query strings, referrers or UTM; Global Privacy Control is honored.
 */
export type MixpanelEnv = Record<string, string | undefined>;

export function mixpanelBoot(env: MixpanelEnv): string {
  const token = String(env.MIXPANEL_PROJECT_TOKEN ?? "").trim();
  const wanted = String(env.MIXPANEL_REGION ?? "").toUpperCase();
  const region = ["US", "EU", "IN"].includes(wanted) ? wanted : "US";
  const on = /^[0-9a-f]{32}$/i.test(token) && String(env.MIXPANEL ?? "").toLowerCase() !== "off";
  const head = "/* Generated by src/mixpanel-boot.ts. Public Mixpanel project token; privacy-first options in mixpanel.vendor.js. */\n";
  if (!on) return `${head}/* Mixpanel is off: MIXPANEL_PROJECT_TOKEN is not set (or MIXPANEL=off). */\n`;
  // Inside the Android app the native Amplitude SDK already counts sessions: no second counter there.
  return `${head}if (typeof initInfinitumMixpanel === "function" && !/\\bArchitectShell\\/android\\b/.test(navigator.userAgent)) {\n  initInfinitumMixpanel(${JSON.stringify(token)}, { region: ${JSON.stringify(region)}, product: "architect" });\n}\n`;
}

export function mixpanelBootResponse(env: MixpanelEnv): Response {
  return new Response(mixpanelBoot(env), {
    headers: { "content-type": "text/javascript; charset=utf-8", "cache-control": "public, max-age=300", "x-content-type-options": "nosniff" },
  });
}
